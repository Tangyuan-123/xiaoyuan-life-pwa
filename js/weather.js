  function getWeather() {
    return new Promise((resolve) => {
      const cached = getCache();
      const fresh = cached && (Date.now() - cached.t < CACHE_MS);
      const tryNet = (coords) => {
        fetchWeather(coords[0], coords[1])
          .then((w) => { const out = Object.assign({ city: cityName(getCity()), fromCache: false }, w); setCache(out); resolve(out); })
          .catch(() => { if (cached) resolve(Object.assign({ fromCache: true }, cached)); else resolve(null); });
      };
      if (fresh && cached) return resolve(Object.assign({ fromCache: true }, cached));
      // 定位需用户在设置里主动开启（默认关闭，避免每次首页自动弹窗/不稳定）；
      // 未开启时直接使用所选城市天气，更稳更快。
      const fallbackToCity = () => {
        const c = getCity();
        const co = CITY_COORDS[c];
        if (co) tryNet(co);
        else if (cached) resolve(Object.assign({ fromCache: true }, cached));
        else resolve(null);
      };
      if (getLocate()) {
        locate().then((coords) => tryNet(coords)).catch(fallbackToCity);
      } else {
        fallbackToCity();
      }
    });
  }

